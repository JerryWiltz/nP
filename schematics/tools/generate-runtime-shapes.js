#!/usr/bin/env node
// Modified: 2026-10-30
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const shapeRoot = path.join(root, 'schematics/shapes');
const output = path.join(root, 'src/np-chart/src/schematicShapes.js');

function runtimeShapes() {
  const shapes = {};
  for (const filename of fs.readdirSync(shapeRoot).filter(name => name.endsWith('.json')).sort()) {
    const shape = JSON.parse(fs.readFileSync(path.join(shapeRoot, filename), 'utf8'));
    if (!/^[a-z][A-Za-z0-9]*$/.test(shape.name) || filename !== `${shape.name}.json` ||
        !shape.topology || !shape.layout) {
      throw new Error(`${filename} has an invalid shape definition`);
    }
    shapes[shape.name] = shape;
  }
  return '// Generated by schematics/tools/generate-runtime-shapes.js from schematics/shapes/*.json.\n' +
    '// Edit the JSON definitions, then run npm run shapes:bundle.\n' +
    `export const schematicShapes = ${JSON.stringify(shapes, null, 4)};\n`;
}

const expected = runtimeShapes();
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
    throw new Error('runtime shape bundle is stale; run npm run shapes:bundle');
  }
  process.stdout.write('Checked runtime shapes.\n');
} else {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
    fs.writeFileSync(output, expected);
  }
  process.stdout.write('Bundled runtime shapes.\n');
}
