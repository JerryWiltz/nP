#!/usr/bin/env node
// Modified: 2026-11-04
'use strict';

const fs = require('fs');
const path = require('path');
const {readCanonicalSymbol, resolveSchematicPaths} = require('./symbol-library');

const {repositoryRoot, symbolRoot} = resolveSchematicPaths(__dirname);
const layoutPath = path.join(repositoryRoot, 'schematics/runtime-symbol-layout.json');
const outputPath = path.join(repositoryRoot, 'src/np-chart/src/schematicSymbols.js');
const constructorMapPath = path.join(repositoryRoot, 'src/np-nport/src/schematicSymbolMap.js');
const nportIndexPath = path.join(repositoryRoot, 'src/np-nport/src/index.js');
const catalog = require('../symbol-catalog.json');
function directRfConstructors() {
  const source = fs.readFileSync(nportIndexPath, 'utf8');
  return [...source.matchAll(/export \{(\w+)\} from '\.\/(.*?)';/g)]
    .filter(([, name, module]) => !module.startsWith('filters/') &&
      !module.startsWith('combining/'))
    .map(([, name]) => name);
}

function generateConstructorSymbolMap() {
  const layouts = JSON.parse(fs.readFileSync(layoutPath, 'utf8')).symbols;
  const symbols = {};
  const variants = {};
  for (const name of directRfConstructors()) {
    const filename = catalog.constructors[name];
    if (!filename || !filename.endsWith('.svg')) {
      throw new Error(`${name} needs a canonical SVG in the symbol catalog`);
    }
    const symbol = filename.slice(0, -4);
    if (!layouts[symbol]) throw new Error(`${name} has no bundled runtime symbol: ${symbol}`);
    symbols[name] = symbol;
    if (catalog.symbolVariants?.[name]) {
      variants[name] = {};
      for (const [option, variantFile] of Object.entries(catalog.symbolVariants[name])) {
        if (!/^[a-z][a-z0-9]*$/.test(option) || !variantFile.endsWith('.svg')) {
          throw new Error(`${name} has an invalid symbol variant`);
        }
        const variant = variantFile.slice(0, -4);
        if (!layouts[variant]) throw new Error(`${name} has no bundled variant: ${variant}`);
        variants[name][option] = variant;
      }
    }
  }
  return '// Generated by schematics/tools/generate-runtime-symbols.js from symbol-catalog.json.\n' +
    '// Edit schematics/symbol-catalog.json, then run npm run symbols:bundle.\n' +
    `export const schematicSymbolMap = ${JSON.stringify(symbols, null, 4)};\n` +
    `export const schematicSymbolVariants = ${JSON.stringify(variants, null, 4)};\n`;
}

function validRectangle(value) {
  return Array.isArray(value) && value.length === 4 &&
    value.every(Number.isFinite) && value[0] < value[2] && value[1] < value[3];
}

function validPoint(value) {
  return Array.isArray(value) && value.length === 2 && value.every(Number.isFinite);
}

function samePoint(left, right) {
  return left[0] === right[0] && left[1] === right[1];
}

function validateLayout(name, layout, ports) {
  if (!validRectangle(layout.bounds) || !validRectangle(layout.bodyBounds) ||
      !layout.leads || !Array.isArray(layout.leads) ||
      !layout.leads.every(lead => Array.isArray(lead) && lead.length === 2 &&
        lead.every(validPoint))) {
    throw new Error(`${name} has invalid runtime bounds or leads`);
  }
  for (const port of ports) {
    if (port[0] < layout.bounds[0] || port[0] > layout.bounds[2] ||
        port[1] < layout.bounds[1] || port[1] > layout.bounds[3]) {
      throw new Error(`${name} has a canonical port outside its runtime bounds`);
    }
    if (!layout.leads.some(lead => lead.some(point => samePoint(point, port)))) {
      throw new Error(`${name} has no lead endpoint at canonical port ${port}`);
    }
  }
  for (const direction of ['entry', 'exit']) {
    if (layout[direction] !== undefined &&
        (!validPoint(layout[direction]) ||
         Math.abs(layout[direction][0]) + Math.abs(layout[direction][1]) !== 1)) {
      throw new Error(`${name} has an invalid ${direction} direction`);
    }
  }
  if (ports.length === 2 && !layout.exit) {
    throw new Error(`${name} needs an exit direction for cascade layout`);
  }
  if (layout.flow) {
    const {throughPorts, shuntPort} = layout.flow;
    const validPort = port => Number.isInteger(port) && port >= 1 && port <= ports.length;
    if (ports.length !== 3 || !Array.isArray(throughPorts) ||
        throughPorts.length !== 2 || !throughPorts.every(validPort) ||
        !validPort(shuntPort) || new Set([...throughPorts, shuntPort]).size !== 3) {
      throw new Error(`${name} needs distinct valid through and shunt ports`);
    }
  }
}

function generateRuntimeSymbols() {
  const configuration = JSON.parse(fs.readFileSync(layoutPath, 'utf8'));
  if (configuration.schemaVersion !== 1 || !configuration.symbols ||
      Array.isArray(configuration.symbols)) {
    throw new Error('runtime symbol layout needs schemaVersion 1 and a symbols object');
  }
  const mapped = new Set([
    ...Object.values(catalog.constructors),
    ...Object.values(catalog.symbolVariants || {}).flatMap(variants => Object.values(variants))
  ]);
  const symbols = {};
  for (const [name, layout] of Object.entries(configuration.symbols)) {
    if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`invalid runtime symbol name: ${name}`);
    const filename = `${name}.svg`;
    if (!mapped.has(filename)) throw new Error(`${filename} is absent from the symbol catalog`);
    const canonical = readCanonicalSymbol(symbolRoot, filename);
    const ports = Object.values(canonical.ports).map(port => [port.x, port.y]);
    validateLayout(name, layout, ports);
    symbols[name] = {
      ports,
      ...layout,
      geometry: canonical.geometry
    };
  }
  return '// Generated by schematics/tools/generate-runtime-symbols.js from canonical SVGs.\n' +
    '// Edit schematics/symbols/ and schematics/runtime-symbol-layout.json, then run npm run symbols:bundle.\n' +
    `export const schematicSymbols = ${JSON.stringify(symbols, null, 4)};\n`;
}

function checkRuntimeSymbols() {
  const expected = generateRuntimeSymbols();
  const actual = fs.readFileSync(outputPath, 'utf8');
  if (actual !== expected) {
    throw new Error('runtime symbol bundle is stale; run npm run symbols:bundle');
  }
  if (!fs.existsSync(constructorMapPath) ||
      fs.readFileSync(constructorMapPath, 'utf8') !== generateConstructorSymbolMap()) {
    throw new Error('constructor symbol map is stale; run npm run symbols:bundle');
  }
  return Object.keys(JSON.parse(fs.readFileSync(layoutPath, 'utf8')).symbols).length;
}

function writeRuntimeSymbols() {
  const expected = generateRuntimeSymbols();
  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (actual !== expected) fs.writeFileSync(outputPath, expected);
  const constructorMap = generateConstructorSymbolMap();
  const currentMap = fs.existsSync(constructorMapPath) ? fs.readFileSync(constructorMapPath, 'utf8') : '';
  if (currentMap !== constructorMap) fs.writeFileSync(constructorMapPath, constructorMap);
  return Object.keys(JSON.parse(fs.readFileSync(layoutPath, 'utf8')).symbols).length;
}

if (require.main === module) {
  try {
    const count = process.argv.includes('--check') ? checkRuntimeSymbols() : writeRuntimeSymbols();
    process.stdout.write(`${process.argv.includes('--check') ? 'Checked' : 'Bundled'} ${count} runtime symbols.\n`);
  } catch (error) {
    process.stderr.write(`generate-runtime-symbols: ${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {checkRuntimeSymbols, generateConstructorSymbolMap,
  generateRuntimeSymbols, writeRuntimeSymbols};
